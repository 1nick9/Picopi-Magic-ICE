#!/usr/bin/env python3
"""
extract_tables.py - pull the `jmp pc+w` byte tables out of the SX28 source
and emit src/patch_tables.c for the Pico port.

The SX28 tables mix `retw` entries with inline `mov w,#N / mov VAR_DC3,w /
jmp LABEL` and `snb FLAG / jmp LABEL` slots, and the loader loop is

        mov w,VAR_DC3 ; call TABLE ; mov indf,w ; inc fsr ; inc VAR_DC3

so one call returns exactly one byte but may first re-seat VAR_DC3.  This
script simulates that walk for every (start, count, flag) combination used by
the firmware, so the byte streams in C are provably the same as the asm.

usage: extract_tables.py <h2o-sx28ORsx48-compile-working.s> [NTSCPS1YFIX75K=1] [ICEFINALDEV1=0]
"""
import re, sys

src_path = sys.argv[1]
opts = {"NTSCPS1YFIX75K": 1, "ICEFINALDEV1": 0, "SX48": 0, "SX48RAM": 0}
out_path = "patch_tables.c"
for a in sys.argv[2:]:
    if "=" in a:
        k, v = a.split("=")
        opts[k] = int(v)
    else:
        out_path = a

lines = open(src_path, encoding="utf-8", errors="replace").read().splitlines()

# ---- crude IFDEF preprocessor ------------------------------------------
def preprocess(lines):
    out, stack = [], []
    for ln in lines:
        s = ln.strip()
        m = re.match(r"IFDEF\s+(\w+)", s, re.I)
        if m:
            stack.append(bool(opts.get(m.group(1), 0)))
            continue
        if re.match(r"ELSE\b", s, re.I):
            stack[-1] = not stack[-1]
            continue
        if re.match(r"ENDIF\b", s, re.I):
            stack.pop()
            continue
        if all(stack):
            out.append(ln)
    return out

raw_lines = lines
lines = preprocess(raw_lines)

def strip(ln):
    return ln.split(";")[0].rstrip()

# ---- table parsing -------------------------------------------------------
def parse_table(label, stop_labels):
    """Return list of slots after `label`'s `jmp pc+w`.  Each slot is
    ('retw', val) | ('setdc3', n) | ('jmp', label) | ('snb', flag) | ('label', name)."""
    i = next(k for k, l in enumerate(lines) if strip(l).strip() == label)
    j = i + 1
    while "pc+w" not in strip(lines[j]):
        j += 1
    slots = []
    for ln in lines[j + 1:]:
        s = strip(ln)
        if not s.strip():
            continue
        tok = s.split()
        first = tok[0]
        if not ln[0].isspace():            # label at column 0
            if first in stop_labels:
                break
            slots.append(("label", first))
            continue
        ins = first.lower()
        args = "".join(tok[1:]).lower()
        if ins == "retw":
            slots.append(("retw", int(args.replace("$", ""), 16)))
        elif ins == "mov" and args.startswith("w,#"):
            n = args[3:]
            n = int(n.replace("$", ""), 16) if n.startswith("$") else int(n)
            slots.append(("movw", n))
        elif ins == "mov" and args == "var_dc3,w":
            slots.append(("setdc3", None))
        elif ins == "jmp":
            slots.append(("jmp", tok[1]))
        elif ins in ("snb", "sb"):
            slots.append((ins, args))
        else:
            raise SystemExit("unexpected table line: " + s)
    # resolve labels to slot indices (labels take no slot)
    idx, labels, body = 0, {}, []
    for sl in slots:
        if sl[0] == "label":
            labels[sl[1]] = idx
        else:
            body.append(sl)
            idx += 1
    return body, labels

def walk(body, labels, start, count, flags):
    """Simulate `count` loader calls starting at VAR_DC3 = start."""
    out, dc3, w = [], start, 0
    for _ in range(count):
        pc = dc3
        while True:
            sl = body[pc]
            if sl[0] == "retw":
                out.append(sl[1]); break
            if sl[0] == "movw":
                w = sl[1]; pc += 1
            elif sl[0] == "setdc3":
                dc3 = w; pc += 1
            elif sl[0] == "jmp":
                pc = labels[sl[1]]
            elif sl[0] == "snb":           # skip next if bit clear
                pc += 2 if not flags.get(sl[1], 0) else 1
            elif sl[0] == "sb":            # skip next if bit set
                pc += 2 if flags.get(sl[1], 0) else 1
        dc3 += 1
    return out

OSD, OSD_L = parse_table("OSDSYS_BIOS_PATCH_DATA", {"PS2_MODE_START"})
LOGO, LOGO_L = parse_table("PS2LOGO_PATCH", {"PS1DRV_PATCHLOAD_v14"})
MECH, MECH_L = parse_table("CDDVD_PATCH_DATA", {"START_CDDVD_PATCH"})

def c_array(name, data, comment):
    body = ", ".join("0x%02x" % b for b in data)
    return "/* %s */\nconst uint8_t %s[%d] = {\n    %s\n};\n" % (comment, name, len(data), body)

out = []
out.append("/* GENERATED by tools/extract_tables.py from h2o-sx28ORsx48-compile-working.s")
out.append("   options: " + ", ".join("%s=%d" % kv for kv in opts.items()))
out.append("   Do not edit - rerun the script. */")
out.append('#include "patch_tables.h"\n')

# OSDSYS (PS2 mode): (name, preload, start, count, flags)
osd_sets = [
    ("osd_v1",   0xc0,  0,  7, {}),
    ("osd_v2v3", 0xd8,  0,  7, {}),
    ("osd_v4",   0x0c,  0,  7, {}),
    ("osd_v5v8", 0x02,  7, 23, {}),
    ("osd_v9",   0x02, 23, 23, {}),
    ("osd_v14",  0x02, 39, 23, {}),
    ("osd_v10",  0x02, 55, 23, {"v12_flag": 0}),
    ("osd_v12",  0x02, 55, 23, {"v12_flag": 1}),
]
for name, pre, start, cnt, fl in osd_sets:
    data = [pre] + walk(OSD, OSD_L, start, cnt, fl)
    out.append(c_array(name, data, "OSDSYS %s: preload $%02x + table[%d..] x%d" % (name, pre, start, cnt)))

# PS1DRV data (PSX mode, non-v14): table[89..99], preload is set at the
# PS1_CONSOLE_PAL_YFIX site ($3c), so no preload here.
ps1drv = walk(OSD, OSD_L, 0x59, 11, {})
out.append(c_array("ps1drv_data", ps1drv, "PS1DRV patch body, OSDSYS table[89..99] (preload $3c added by caller)"))

# PS2LOGO (loaded to SRAM k=0..)
logo_v1v9  = walk(LOGO, LOGO_L, 0, 110, {"v14_flag": 0, "v10_flag": 0})
logo_v10v12= walk(LOGO, LOGO_L, 0, 110, {"v14_flag": 0, "v10_flag": 1})
logo_v14   = walk(LOGO, LOGO_L, 0, 123, {"v14_flag": 1, "v10_flag": 1})
out.append(c_array("logo_sram_v1v9",   logo_v1v9,   "PS2LOGO SRAM image, v1-v9 (110 bytes)"))
out.append(c_array("logo_sram_v10v12", logo_v10v12, "PS2LOGO SRAM image, v10-v12 (110 bytes)"))
out.append(c_array("logo_sram_v14",    logo_v14,    "PS2LOGO SRAM image, v14 (123 bytes)"))

# V14 PS1DRV: 39 bytes of PS2LOGO (v14 flags), patched by SET_V14DRV, plus
# 16 bytes of OSDSYS table[100..115]
v14drv = walk(LOGO, LOGO_L, 0, 39, {"v14_flag": 1, "v10_flag": 1})
# fsr -> k : $15..$1f = k 0..10, then $30+ bank*0x20 + i = 11 + bank*16 + i
def fsr_to_k(a):
    if 0x15 <= a <= 0x1f: return a - 0x15
    return 11 + ((a - 0x30) // 0x20) * 16 + ((a - 0x30) % 0x20)
for addr, val in ((0x34, 0x14), (0x35, 0x02), (0x50, 0x20), (0x54, 0x5c), (0x55, 0x25), (0x5a, 0x08)):
    v14drv[fsr_to_k(addr)] = val
assert fsr_to_k(0x5c) == 39
v14drv += walk(OSD, OSD_L, 100, 16, {})
out.append(c_array("ps1drv_v14_sram", v14drv, "V14 PS1DRV SRAM image: PS2LOGO[0..38] + SET_V14DRV edits + OSDSYS table[100..115]"))

# DEV1 - both variants are emitted, the header picks one with ICEFINALDEV1
saved = opts["ICEFINALDEV1"]
for flag, name, n, desc in ((0, "dev1_patch_h2o", 115, "H2O"), (1, "dev1_patch_ice", 119, "ICE Final")):
    opts["ICEFINALDEV1"] = flag
    lines = preprocess(raw_lines)
    D, DL = parse_table("BIOS_PATCH_DEV1", {"DEV1_MODE_LOAD_START"})
    out.append(c_array(name, walk(D, DL, 0, n, {}), "BIOS_PATCH_DEV1 (%s), bytes 7,8 are replaced per console" % desc))
opts["ICEFINALDEV1"] = saved
lines = preprocess(raw_lines)

# mechacon region nibbles
mech = walk(MECH, MECH_L, 0, 24, {})
out.append(c_array("cddvd_patch_data", mech, "CDDVD_PATCH_DATA: 8 bytes each USA/PAL/JAP, sent high nibble then low nibble on B,G,H,I"))

open(out_path, "w").write("\n".join(out))
print("\n".join(out))
